def _grounded_memory_case(
    *,
    case_id: str,
    title: str,
    fact_id: str,
    user_query: str,
    expected_markers: list[str],
    forbidden_claims: list[str] | None = None,
    recent_history: list[ChatHistoryEntry] | None = None,
) -> RagEvaluationCase:
    memory = get_memory_setup_by_fact_id(fact_id)
    return RagEvaluationCase(
        case_id=case_id,
        title=title,
        profile=EVA_NOVAK_PROFILE,
        recent_history=recent_history or [],
        memory_evidence_items=[memory],
        user_query=user_query,
        expected_behavior="grounded_answer",
        expected_evidence_markers=expected_markers,
        forbidden_claims=forbidden_claims or [],
        minimum_required_evidence_count=1,
    )


def _grounded_rag_case(
    *,
    case_id: str,
    title: str,
    fact_id: str,
    user_query: str,
    expected_markers: list[str],
    forbidden_claims: list[str] | None = None,
) -> RagEvaluationCase:
    rag = get_rag_setup_by_fact_id(fact_id)
    return RagEvaluationCase(
        case_id=case_id,
        title=title,
        profile=EVA_NOVAK_PROFILE,
        retrieved_evidence_items=[rag],
        user_query=user_query,
        expected_behavior="grounded_answer",
        expected_evidence_markers=expected_markers,
        forbidden_claims=forbidden_claims or [],
        minimum_required_evidence_count=1,
    )


def _lack_case(
    *,
    case_id: str,
    title: str,
    user_query: str,
    forbidden_claims: list[str],
) -> RagEvaluationCase:
    return RagEvaluationCase(
        case_id=case_id,
        title=title,
        profile=EVA_NOVAK_PROFILE,
        user_query=user_query,
        expected_behavior="lack_of_evidence",
        should_require_lack_of_evidence=True,
        forbidden_claims=forbidden_claims,
    )


